-- Fichar sin conexión (plan L; ADR 054).
--
-- Un técnico en una cámara frigorífica o en un sótano no tiene cobertura. La
-- app guarda el fichaje con su hora y lo manda al volver la red; el servidor
-- lo aplica con la hora en que ocurrió, no con la de llegada.

-- ---------------------------------------------------------------------
-- Desde dónde se fichó
-- ---------------------------------------------------------------------
-- null en lo anterior a esta migración (no se sabe), salvo lo del kiosco,
-- que sí consta por kiosco_id.
ALTER TABLE registros ADD COLUMN origen VARCHAR(20);
ALTER TABLE registros ADD CONSTRAINT ck_registros_origen
    CHECK (origen IN ('WEB', 'APP', 'KIOSCO', 'APP_SIN_CONEXION'));
UPDATE registros SET origen = 'KIOSCO' WHERE kiosco_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- Lo que llegó demasiado tarde
-- ---------------------------------------------------------------------
-- Un fichaje sin conexión que llega pasadas 72 h se guarda con su hora, pero
-- no se da por bueno solo: cuenta como incidencia y no deja firmar el mes
-- hasta que un gestor lo da por bueno o lo corrige. Como jornada_incompleta.
ALTER TABLE registros ADD COLUMN revisar_por_llegar_tarde BOOLEAN NOT NULL DEFAULT FALSE;

-- ---------------------------------------------------------------------
-- Lo ya recibido, para no aplicarlo dos veces
-- ---------------------------------------------------------------------
-- Si la respuesta se pierde por el camino, la app vuelve a mandar el mismo
-- fichaje con el mismo id_cliente: se contesta lo que se contestó la primera
-- vez. Se borra a los 30 días (ConservacionDeDatos): la app reintenta durante
-- horas, no durante meses.
CREATE TABLE fichajes_recibidos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT       NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
    id_cliente   UUID         NOT NULL,
    registro_id  BIGINT       REFERENCES registros (id) ON DELETE CASCADE,
    resultado    VARCHAR(20)  NOT NULL,
    motivo       VARCHAR(500),
    recibido_en  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_fichajes_recibidos UNIQUE (usuario_id, id_cliente),
    CONSTRAINT ck_fichajes_recibidos_resultado CHECK (resultado IN ('APLICADO', 'A_REVISAR', 'RECHAZADO'))
);

CREATE INDEX ix_fichajes_recibidos_recibido_en ON fichajes_recibidos (recibido_en);

-- ---------------------------------------------------------------------
-- La auditoría gana una acción: el gestor da por bueno lo que llegó tarde
-- ---------------------------------------------------------------------
-- 🚨 El CHECK se reemplaza ENTERO: las once de V25 más la nueva.
ALTER TABLE auditoria_fichaje DROP CONSTRAINT auditoria_fichaje_accion_check;
ALTER TABLE auditoria_fichaje ADD CONSTRAINT auditoria_fichaje_accion_check
    CHECK (accion IN (
        'CREACION',
        'MODIFICACION',
        'CORRECCION',
        'ANULACION',
        'SOLICITUD_CORRECCION',
        'RECHAZO_CORRECCION',
        'DISPUTA',
        'PAUSA_ANADIDA',
        'PAUSA_ANULADA',
        'PROYECTO_CAMBIADO',
        'REPARTO_PROYECTOS',
        'DADO_POR_BUENO'
    ));
